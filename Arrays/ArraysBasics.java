public class ArraysBasics {
    static void main(String[] args) {
        int[] x={6,19,11,18,69,171};
        //indexing
        System.out.println(x[0]);
        //for updating element
        x[4]=35;
        System.out.println(x[4]);
        //Another way to store value in array
        int[] arr=new int[6];
        arr[0]=1;
        arr[1]=9;
        arr[2]=141;
        arr[3]=183;
        arr[4]=169;
        arr[5]=1712;
        System.out.println(arr[4]);


    }
}
